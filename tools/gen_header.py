"""
gen_header.py — Automatic C Header Generator from Device JSON Symbol Maps

Generates a standalone, drift-free C header (.h) directly from a device definition
JSON file (.json), ensuring 100% consistency with zero manual duplication.
"""

import os
import sys
import json
import re

def generate_header(json_path, out_h_path=None):
    with open(json_path, "r", encoding="utf-8") as f:
        data = json.load(f)

    device_name = data.get("device", "Unknown Device")
    soc = data.get("soc", "Unknown SoC")
    fw_ver = data.get("firmware_version", "v1")
    sha256 = data.get("stock_lk_sha256", "N/A")
    base_name = os.path.basename(json_path).replace(".json", "")
    guard_name = re.sub(r"[^A-Za-z0-9_]", "_", base_name).upper() + "_H"

    lines = []
    lines.append("/* SPDX-License-Identifier: GPL-3.0-or-later */")
    lines.append("/*")
    lines.append(f" * {base_name}.h — Golden Reference Stock Symbol & Hardware Register Map")
    lines.append(f" * Target: {device_name} (Firmware Baseline {fw_ver})")
    lines.append(f" * SoC: {soc} | Arch: {data.get('arch', 'aarch64')}")
    lines.append(f" * Stock Container SHA256: {sha256}")
    lines.append(" *")
    lines.append(" * AUTO-GENERATED by tools/gen_header.py — All addresses byte-verified.")
    lines.append(" */\n")

    lines.append(f"#ifndef {guard_name}")
    lines.append(f"#define {guard_name}\n")
    lines.append("#include <stdint.h>\n")

    # Subpartitions
    subparts = data.get("subpartitions", {})
    if subparts:
        lines.append("/* --- Subpartition Offsets & Extents inside Composite lk.img --- */")
        lines.append("#define MKIMG_HDR_SIZE               512ULL\n")
        for sub_id, info in subparts.items():
            u = sub_id.upper()
            hdr_ofs = info.get("header_offset", info.get("offset", "0x000000"))
            pay_ofs = info.get("payload_offset", f"0x{int(hdr_ofs, 16)+512:06X}")
            pay_sz = info.get("payload_size", info.get("size", "0x0"))
            sz_bytes = info.get("size_bytes", int(pay_sz, 16) if pay_sz.startswith("0x") else 0)
            span = info.get("container_span", "0x0")
            load_addr = info.get("load_addr")

            lines.append(f"#define SUBPART_{u}_OFFSET            {hdr_ofs}ULL  /* mkimg header container offset */")
            lines.append(f"#define SUBPART_{u}_PAYLOAD_OFFSET    {pay_ofs}ULL  /* raw payload container offset (header + 512) */")
            lines.append(f"#define SUBPART_{u}_SIZE              {pay_sz}ULL  /* {sz_bytes:,} bytes (raw execution payload) */")
            if span and span != "0x0":
                lines.append(f"#define SUBPART_{u}_CONTAINER_SPAN    {span}ULL")
            if load_addr and load_addr.startswith("0x"):
                lines.append(f"#define SUBPART_{u}_LOAD_VIRT         {load_addr}ULL")
            lines.append("")

    # Symbols: LK
    symbols = data.get("symbols", {})
    lk_syms = symbols.get("lk", {})
    if lk_syms:
        lines.append("/* --- Stock Little Kernel (LK / BL33) Verified Functions --- */")
        for sym_name, sym_info in lk_syms.items():
            addr = sym_info["addr"]
            u = sym_name.upper()
            if sym_name == "_start":
                lines.append(f"#define ADDR_LK__START               {addr}ULL")
                lines.append("#define ADDR_LK_ENTRY                ADDR_LK__START")
            elif sym_name == "arch_clean_cache_disable_mmu_and_jump":
                lines.append(f"#define ADDR_LK_ARCH_CLEAN_CACHE_DISABLE_MMU_AND_JUMP {addr}ULL")
                lines.append("#define ADDR_LK_ARCH_DISABLE_MMU_JMP ADDR_LK_ARCH_CLEAN_CACHE_DISABLE_MMU_AND_JUMP")
            elif sym_name == "smc_boot_linux_trampoline":
                lines.append(f"#define ADDR_LK_SMC_BOOT_LINUX_TRAMPOLINE {addr}ULL")
                lines.append("#define ADDR_LK_SMC_BOOT_TRAMPOLINE  ADDR_LK_SMC_BOOT_LINUX_TRAMPOLINE")
            else:
                lines.append(f"#define ADDR_LK_{u:<28} {addr}ULL")
        lines.append("")

    # Symbols: BL2_EXT
    bl2_syms = symbols.get("bl2_ext", {})
    if bl2_syms:
        lines.append("/* --- Stock Bootloader Extension (BL2_EXT / EL3) Verified Functions --- */")
        for sym_name, sym_info in bl2_syms.items():
            addr = sym_info["addr"]
            u = sym_name.upper()
            if sym_name == "_start":
                lines.append(f"#define ADDR_BL2_EXT__START          {addr}ULL")
                lines.append("#define ADDR_BL2_EXT_ENTRY           ADDR_BL2_EXT__START")
            elif sym_name == "spsr_drop_routine":
                lines.append(f"#define ADDR_BL2_EXT_SPSR_DROP_ROUTINE {addr}ULL")
                lines.append("#define ADDR_BL2_EXT_SPSR_ROUTINE    ADDR_BL2_EXT_SPSR_DROP_ROUTINE")
            elif sym_name == "atf_handoff_jump":
                lines.append(f"#define ADDR_BL2_EXT_ATF_HANDOFF_JUMP {addr}ULL")
                lines.append("#define ADDR_BL2_EXT_ATF_JUMP        ADDR_BL2_EXT_ATF_HANDOFF_JUMP")
            else:
                lines.append(f"#define ADDR_BL2_EXT_{u:<24} {addr}ULL")
        lines.append("")

    # Symbols: AEE
    aee_syms = symbols.get("aee", {})
    if aee_syms:
        lines.append("/* --- Stock Exception Engine (AEE / kedump) --- */")
        for sym_name, sym_info in aee_syms.items():
            addr = sym_info["addr"]
            lines.append(f"#define ADDR_AEE_{sym_name.upper():<28} {addr}ULL")
        lines.append("")

    # Registers
    regs = data.get("registers", {})
    if regs:
        lines.append("/* --- SoC Hardware Peripherals & MMIO --- */")
        for reg_name, reg_val in regs.items():
            lines.append(f"#define {reg_name:<28} {reg_val}ULL")
        lines.append("")

    # Keycodes
    keycodes = data.get("keycodes", {})
    if keycodes:
        lines.append("/* --- Keypad & Input Keycodes --- */")
        for k_name, k_val in keycodes.items():
            lines.append(f"#define KEY_{k_name:<24} {k_val}")
        lines.append("")

    # Zero Regions
    zero_regs = data.get("zero_regions", {}).get("lk", {})
    if zero_regs:
        lines.append("/* --- Zero-Filled (.text) Executable Padding Regions (No Dead Code Reuse) --- */")
        for z_name, z_info in zero_regs.items():
            f_ofs = z_info["file_offset"]
            v_start = z_info["addr_start"]
            sz = z_info["size_bytes"]
            lines.append(f"/* {z_name}: {z_info.get('desc', '')} ({sz:,} bytes pure 0x00) */")
            lines.append(f"#define {z_name}_OFFSET         {f_ofs}ULL")
            lines.append(f"#define {z_name}_VIRT           {v_start}ULL")
            lines.append(f"#define {z_name}_SIZE           {sz}ULL")
            if "recommended_hook_addr" in z_info:
                lines.append(f"#define PROOF_HOOK_TARGET_VIRT       {z_info['recommended_hook_addr']}ULL")
            lines.append("")

    # Unallocated Flash
    unalloc = data.get("unallocated_flash", {})
    if unalloc:
        lines.append("/* --- Container Flash Partition Free Space (lk.img) --- */")
        lines.append(f"#define UNALLOCATED_FLASH_OFFSET     {unalloc['offset_start']}ULL")
        lines.append(f"#define UNALLOCATED_FLASH_SIZE       0x{unalloc['free_space_bytes']:X}ULL  /* {unalloc['free_space_bytes']:,} bytes */")
        lines.append(f"#define CONTAINER_TOTAL_SIZE         0x{unalloc['container_size_bytes']:X}ULL  /* {unalloc['container_size_bytes']:,} bytes (4 MiB) */\n")

    # Hook Sites
    hooks = data.get("hooks", {})
    if hooks:
        lines.append("/* --- Primary Safe Hook Sites --- */")
        hook_site_names = {
            "HOOK_TARGET_INIT_CALL": "HOOK_SITE_TARGET_INIT_CALL",
            "HOOK_APP_FASTBOOT": "HOOK_SITE_FASTBOOT_ENTRY_PTR",
            "HOOK_APP_MTBOOT": "HOOK_SITE_MTBOOT_ENTRY_PTR",
            "HOOK_KERNEL_DECOMP_CALL": "HOOK_SITE_KERNEL_DECOMP_CALL",
            "HOOK_BL2_EXT_SPSR": "HOOK_SITE_BL2_EXT_SPSR",
        }
        for h_key, def_name in hook_site_names.items():
            if h_key in hooks:
                target = hooks[h_key]["target"]
                desc = hooks[h_key].get("desc", "")
                lines.append(f"#define {def_name:<28} {target}ULL  /* {desc} */")
        lines.append("")

    # Dead Code Caves
    dead_code = data.get("dead_code", {}).get("lk", {})
    if dead_code:
        lines.append("/* --- Hardware- & Build-Specific Dead Code Caves (.text) --- */")
        for dc_name, dc_info in dead_code.items():
            f_ofs = dc_info["file_offset"]
            v_start = dc_info["addr_start"]
            sz = dc_info["size_bytes"]
            cond = dc_info.get("condition", "")
            lines.append(f"/* {dc_name}: {cond} */")
            lines.append(f"#define {dc_name}_OFFSET    {f_ofs}ULL")
            lines.append(f"#define {dc_name}_VIRT      {v_start}ULL")
            lines.append(f"#define {dc_name}_SIZE      {sz}ULL")
            lines.append("")

    lines.append(f"#endif /* {guard_name} */\n")

    output_content = "\n".join(lines)
    if out_h_path:
        with open(out_h_path, "w", encoding="utf-8") as f:
            f.write(output_content)
        print(f"[+] Header generated: {out_h_path}")
    else:
        print(output_content)
    return output_content

def main():
    if len(sys.argv) < 2:
        print(f"Usage: {sys.argv[0]} <path/to/device.json> [output_path.h]")
        sys.exit(1)

    json_path = sys.argv[1]
    out_h = sys.argv[2] if len(sys.argv) > 2 else json_path.replace(".json", ".h")
    generate_header(json_path, out_h)

if __name__ == "__main__":
    main()
